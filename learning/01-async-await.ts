// ฟังก์ชันจำลอง "งานที่ใช้เวลา" เช่น ถามฐานข้อมูล / เรียก API
// (ของจริงคือ prisma.user.findMany() ฯลฯ แต่ตรงนี้ปลอมด้วย setTimeout แทน)
function สั่งกาแฟ(ชื่อเมนู: string): Promise<string> {
  return new Promise((resolve) => {
    console.log(`  -> รับออเดอร์ "${ชื่อเมนู}" แล้ว กำลังชง...`);
    setTimeout(() => {
      resolve(`${ชื่อเมนู} เสร็จแล้ว!`);
    }, 2000); // แกล้งทำว่าชงกาแฟใช้เวลา 2 วินาที
  });
}

// ===== ตัวอย่างที่ 1: ไม่ใส่ await (ผิด) =====
function ตัวอย่างผิด() {
  console.log("\n=== ตัวอย่างที่ 1: ลืมใส่ await ===");
  const ผลลัพธ์ = สั่งกาแฟ("ลาเต้");
  console.log("ผลลัพธ์ที่ได้:", ผลลัพธ์);
  // จะเห็นว่า print ออกมาเป็น "Promise { <pending> }" ไม่ใช่ข้อความจริง
  // เพราะเราไม่ได้ "รอ" ให้กาแฟชงเสร็จก่อน รีบมาพิมพ์เลย
}

// ===== ตัวอย่างที่ 2: ใส่ await (ถูก) =====
async function ตัวอย่างถูก() {
  console.log("\n=== ตัวอย่างที่ 2: ใส่ await ===");
  const ผลลัพธ์ = await สั่งกาแฟ("ลาเต้");
  console.log("ผลลัพธ์ที่ได้:", ผลลัพธ์);
  // รอบนี้โปรแกรมจะ "หยุดรอ" ตรงบรรทัด await จนกว่ากาแฟจะเสร็จ
  // ถึงจะพิมพ์บรรทัดถัดไป
}

// ===== ตัวอย่างที่ 3: สองแก้วพร้อมกัน (Promise.all) =====
async function สองแก้วพร้อมกัน() {
  console.log("\n=== ตัวอย่างที่ 3: สั่ง 2 แก้วพร้อมกัน ===");
  console.time("เวลาที่ใช้");
  const [แก้ว1, แก้ว2] = await Promise.all([
    สั่งกาแฟ("ลาเต้"),
    สั่งกาแฟ("อเมริกาโน่"),
  ]);
  console.log(แก้ว1, "|", แก้ว2);
  console.timeEnd("เวลาที่ใช้"); // ควรใช้เวลาประมาณ 2 วิ (ไม่ใช่ 4 วิ เพราะชงพร้อมกัน)
}

// รันทุกตัวอย่างเรียงกัน
async function main() {
  ตัวอย่างผิด();
  await new Promise((r) => setTimeout(r, 2500)); // รอให้ตัวอย่างที่ 1 จบก่อน (เดี๋ยวอธิบาย)

  await ตัวอย่างถูก();
  await สองแก้วพร้อมกัน();
}

main();

