// ==========================================
// 1. Arrow function — แค่อีกวิธีเขียนฟังก์ชัน
// ==========================================
console.log("=== 1. Arrow function ===");

// แบบเก่า (function ธรรมดา)
function บวกเลขแบบเก่า(a: number, b: number) {
  return a + b;
}

// แบบ arrow function — ความหมายเดียวกันเป๊ะ แค่เขียนสั้นกว่า
const บวกเลข = (a: number, b: number) => {
  return a + b;
};

// arrow function แบบสั้นสุด — ถ้ามีแค่ return บรรทัดเดียว ตัด { return ... } ออกได้
const บวกเลขสั้น = (a: number, b: number) => a + b;

console.log(บวกเลขแบบเก่า(2, 3)); // 5
console.log(บวกเลข(2, 3));        // 5 (เหมือนกัน)
console.log(บวกเลขสั้น(2, 3));     // 5 (เหมือนกัน)

// ทำไมโค้ดเว็บคุณใช้ arrow function เกือบหมด?
// เพราะเขียนสั้น + ใช้เป็นค่าที่ส่งต่อได้ง่าย เช่น onClick={() => setQty(1)}
// (ฟังก์ชันเปล่าๆ ที่สร้างขึ้นมาแล้วส่งเข้าไปในบรรทัดเดียว ไม่ต้องตั้งชื่อ)

// ==========================================
// 2. Destructuring — แกะค่าออกจาก object/array
// ==========================================
console.log("\n=== 2. Destructuring ===");

const ผู้ใช้ = { ชื่อ: "สมชาย", อายุ: 25, ตำแหน่ง: "ADMIN" };

// แบบเก่า
const ชื่อเก่า = ผู้ใช้.ชื่อ;
const อายุเก่า = ผู้ใช้.อายุ;

// แบบ destructuring — แกะหลายค่าออกมาทีเดียว ชื่อตัวแปรต้องตรงกับ key ใน object
const { ชื่อ, อายุ } = ผู้ใช้;
console.log(ชื่อ, อายุ); // สมชาย 25

// เจอในโค้ดจริงบ่อยมาก เช่น:
//   const { assets, totalPages } = result.data;
// แปลว่า "ใน result.data มี key ชื่อ assets กับ totalPages แกะสองอันนี้ออกมาเป็นตัวแปรแยก"

// array destructuring (ต่างจาก object ตรงใช้ [] แทน {} และเรียงตามตำแหน่ง ไม่ใช่ชื่อ)
const คู่สี = ["แดง", "น้ำเงิน"];
const [สีแรก, สีสอง] = คู่สี;
console.log(สีแรก, สีสอง); // แดง น้ำเงิน

// นี่แหละที่มาของ const [isSubmitting, setIsSubmitting] = useState(false)
// useState คืน array 2 ช่อง ช่องแรก=ค่า ช่องสอง=ฟังก์ชันเปลี่ยนค่า เราแกะออกมาตั้งชื่อเอง

// ==========================================
// 3. Template literal — เอาตัวแปรมาแทรกในข้อความ
// ==========================================
console.log("\n=== 3. Template literal ===");

const จำนวน = 3;
const หน่วย = "ชิ้น";

// แบบเก่า ต่อ string ด้วย +
const ข้อความเก่า = "เหลือ " + จำนวน + " " + หน่วย;

// แบบ template literal — ใช้ backtick ` ` (ไม่ใช่ ' หรือ ") แล้วแทรกตัวแปรด้วย ${...}
const ข้อความใหม่ = `เหลือ ${จำนวน} ${หน่วย}`;

console.log(ข้อความเก่า); // เหลือ 3 ชิ้น
console.log(ข้อความใหม่); // เหลือ 3 ชิ้น (เหมือนกัน แค่อ่านง่ายกว่าเวลามีตัวแปรเยอะ)

// ==========================================
// 4. Ternary (? :) — if/else แบบย่อ ใช้ในบรรทัดเดียว
// ==========================================
console.log("\n=== 4. Ternary ===");

const คงเหลือ = 0;

// แบบ if/else ธรรมดา
let ข้อความสต็อกเก่า;
if (คงเหลือ > 0) {
  ข้อความสต็อกเก่า = "มีของ";
} else {
  ข้อความสต็อกเก่า = "ของหมด";
}

// แบบ ternary — โครงสร้าง: เงื่อนไข ? ค่าถ้าจริง : ค่าถ้าเท็จ
const ข้อความสต็อกใหม่ = คงเหลือ > 0 ? "มีของ" : "ของหมด";

console.log(ข้อความสต็อกเก่า);  // ของหมด
console.log(ข้อความสต็อกใหม่);  // ของหมด (เหมือนกัน)

// เจอบ่อยมากใน JSX เพราะ JSX ใช้ if ธรรมดาไม่ได้ ต้องใช้ ternary แทน เช่น:
//   {isSubmitting ? "กำลังยืม..." : "ยืนยันยืม"}
// แปลว่า "ถ้า isSubmitting เป็น true ให้โชว์คำว่า กำลังยืม... ไม่งั้นโชว์ ยืนยันยืม"

// ==========================================
