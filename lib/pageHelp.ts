const baht = (n: number) => n.toLocaleString("th-TH");

// The worked example for the daily-pay rule, computed with the same formula the
// wage report uses (so the example can never disagree with the real result).
const ROUND_UP_TEXT = `${Math.floor(ROUND_UP_TO_FULL_DAY_MINUTES / 60)}.${(ROUND_UP_TO_FULL_DAY_MINUTES % 60) / 10}`;

function proratedPayExample() {
  const dayRate = 400;
  const hours = 6;
  const pay = Math.round((dayRate / REGULAR_HOURS_PER_DAY) * hours);
  return [
    `เกรดอัตรา ${baht(dayRate)} บาท/วัน ทำงานวันนั้น ${hours} ชม.`,
    `ค่าแรง = ${baht(dayRate)} ÷ ${REGULAR_HOURS_PER_DAY} × ${hours} = ${baht(pay)} บาท`,
    `ถ้าทำ ${ROUND_UP_TEXT} ชม. ขึ้นไป (= 7 ชม. 30 นาที) นับเป็นเต็มวัน ${REGULAR_HOURS_PER_DAY} ชม. = ${baht(dayRate)} บาท`,
  ].join("\n");
}

function dailyPayExample() {
  const baseRate = 500;
  const elapsedHours = 11.5; // 08:00 -> 19:30
  const worked = elapsedHours - LUNCH_BREAK_HOURS;
  const ot = worked - REGULAR_HOURS_CAP;
  const otPay = Math.round(ot * (baseRate / REGULAR_HOURS_PER_DAY) * OT_MULTIPLIER);
  return [
    `เกรดออฟฟิศ ${baht(baseRate)} บาท/วัน เข้า 08:00 ออก 19:30`,
    `ผ่านไป ${elapsedHours} ชม. − พักเที่ยง ${LUNCH_BREAK_HOURS} ชม. = ทำงาน ${worked} ชม. → ปกติ ${REGULAR_HOURS_CAP} + OT ${ot} ชม.`,
    `ค่า OT = ${ot} × (${baht(baseRate)} ÷ ${REGULAR_HOURS_PER_DAY}) × ${OT_MULTIPLIER} = ${baht(otPay)} บาท`,
    `ยอดวันนั้น = ${baht(baseRate)} + ${baht(otPay)} = ${baht(baseRate + otPay)} บาท`,
  ].join("\n");
}

